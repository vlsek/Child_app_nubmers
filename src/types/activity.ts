import type { Component } from 'vue'

/**
 * Активность (мини-игра) внутри уровня-цифры.
 *
 * Компонент активности получает проп `level: NumberLevel` и сообщает о победе
 * событием `complete`. Рамку (кнопки «назад» и «звук», праздник, звезда, переходы)
 * рисует оболочка ActivityView — в активности её делать не надо.
 */
export interface ActivityDef {
  /** Уникальный в пределах цифры id, латиницей: `wheels`, `balloons`. */
  id: string
  /** Название для скринридера и разработчика (ребёнок читать не умеет). */
  title: string
  /** Картинка плитки в хабе уровня; получает проп `level`. */
  preview: Component
  /** Сам экран активности, грузится лениво. */
  component: () => Promise<{ default: Component }>
}
