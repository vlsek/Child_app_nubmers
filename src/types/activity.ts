import type { Component } from 'vue'

/**
 * Задание внутри уровня-цифры. Малыш нажимает на машинку, и задания идут
 * по очереди (последовательность строит SequenceView).
 *
 * Компонент задания получает проп `level: NumberLevel` и шлёт `complete`, когда
 * ребёнок справился. Рамку (кнопки, прогресс, похвала, «пропустить») рисует оболочка.
 */
export interface ActivityDef {
  /** Уникальный в пределах цифры id, латиницей: `wheels`, `balloons`. */
  id: string
  /** Название для разработчика и скринридера (ребёнок читать не умеет). */
  title: string
  /** Сам экран задания, грузится лениво. */
  component: () => Promise<{ default: Component }>
}
